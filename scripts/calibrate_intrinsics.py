#!/usr/bin/env python3
"""
Camera intrinsic calibration from a folder of ChArUco board photos.

Matches the board generated by scripts/generate_charuco_board.py: 5x7 squares,
DICT_6X6_250. Pass the square/marker size you actually measured with a ruler
(off a print or a tablet screen) -- not the filename's nominal size, unless
you verified it matches.

Usage:
    python3 scripts/calibrate_intrinsics.py \
        --images path/to/photos/ \
        --square-size 28 --marker-size 20 \
        --out configs/camera_intrinsics.yaml

Take 20-30 photos of the board first: vary angle, tilt, and distance, and
cover different parts of the frame (corners, not just center).
"""

from __future__ import annotations

import argparse
import glob
import os
import sys

import cv2
import numpy as np


def find_images(images_dir: str) -> list[str]:
    exts = ("*.jpg", "*.jpeg", "*.png", "*.JPG", "*.JPEG", "*.PNG")
    paths: list[str] = []
    for ext in exts:
        paths.extend(glob.glob(os.path.join(images_dir, ext)))
    return sorted(paths)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--images", required=True, help="Directory of calibration photos.")
    parser.add_argument("--square-size", type=float, required=True, help="Measured square size in mm.")
    parser.add_argument("--marker-size", type=float, required=True, help="Measured marker size in mm.")
    parser.add_argument("--squares-x", type=int, default=5)
    parser.add_argument("--squares-y", type=int, default=7)
    parser.add_argument("--dictionary", default="6X6_250",
                        help="ArUco dictionary of the board, e.g. 6X6_250 (default) or 4X4_50.")
    parser.add_argument("--out", default="configs/camera_intrinsics.yaml")
    args = parser.parse_args()

    image_paths = find_images(args.images)
    if len(image_paths) < 10:
        print(f"Found only {len(image_paths)} images in {args.images} -- need at least ~10-15 for a usable "
              f"calibration (20-30 is better). Take more photos at varied angles/distances/positions in frame.")
        sys.exit(1)
    print(f"Found {len(image_paths)} images.")

    attribute = f"DICT_{args.dictionary.upper().replace('DICT_', '')}"
    if not hasattr(cv2.aruco, attribute):
        sys.exit(f"Unknown --dictionary {args.dictionary!r}")
    aruco_dict = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, attribute))
    board = cv2.aruco.CharucoBoard(
        (args.squares_x, args.squares_y),
        args.square_size / 1000.0,
        args.marker_size / 1000.0,
        aruco_dict,
    )
    detector = cv2.aruco.CharucoDetector(board)

    all_obj_points = []
    all_img_points = []
    image_size = None
    used, skipped = 0, 0

    for path in image_paths:
        img = cv2.imread(path)
        if img is None:
            print(f"  skip (unreadable): {path}")
            skipped += 1
            continue
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        if image_size is None:
            image_size = gray.shape[::-1]  # (width, height)

        charuco_corners, charuco_ids, _marker_corners, _marker_ids = detector.detectBoard(gray)
        if charuco_corners is None or len(charuco_corners) < 6:
            print(f"  skip (board not found well): {os.path.basename(path)}")
            skipped += 1
            continue

        obj_points, img_points = board.matchImagePoints(charuco_corners, charuco_ids)
        if obj_points is None or len(obj_points) < 6:
            print(f"  skip (could not match object points): {os.path.basename(path)}")
            skipped += 1
            continue

        all_obj_points.append(obj_points)
        all_img_points.append(img_points)
        used += 1

    print(f"\nUsed {used} images, skipped {skipped}.")
    if used < 10:
        print("Too few usable images to calibrate reliably. Take more photos with the board clearly "
              "visible and flat, varying angle/distance/position.")
        sys.exit(1)

    reproj_error, camera_matrix, dist_coeffs, _rvecs, _tvecs = cv2.calibrateCamera(
        all_obj_points, all_img_points, image_size, None, None
    )

    print(f"\nReprojection error: {reproj_error:.4f} px (lower is better; under ~0.5 is good, "
          f"over ~1.0 means retake photos)")
    print(f"Camera matrix:\n{camera_matrix}")
    print(f"Distortion coefficients:\n{dist_coeffs.ravel()}")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    fs = cv2.FileStorage(args.out, cv2.FILE_STORAGE_WRITE)
    fs.write("image_width", image_size[0])
    fs.write("image_height", image_size[1])
    fs.write("camera_matrix", camera_matrix)
    fs.write("dist_coeffs", dist_coeffs)
    fs.write("reprojection_error", reproj_error)
    fs.release()
    print(f"\nWrote {args.out}")


if __name__ == "__main__":
    main()
